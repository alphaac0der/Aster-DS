import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');

export const COMPONENT_CSS_SOURCES = [
  'components/base/base.css',
  'components/button/button.css',
  'components/input/input.css',
  'components/table/table.css',
  'components/checkbox/checkbox.css',
  'components/radio/radio.css',
  'components/switch/switch.css',
  'components/textarea/textarea.css',
  'components/select/select.css',
  'components/slider/slider.css',
  'components/badge/badge.css',
  'components/alert/alert.css',
  'components/progress/progress.css',
  'components/skeleton/skeleton.css',
  'components/tooltip/tooltip.css',
  'components/toast/toast.css',
  'components/dialog/dialog.css',
  'components/dropdown/dropdown.css',
  'components/popover/popover.css',
  'components/tabs/tabs.css',
  'components/accordion/accordion.css',
  'components/drawer/drawer.css'
];

export const COMPONENT_JS_SOURCES = [
  'components/button/button.js',
  'components/input/input.js',
  'components/table/table.js',
  'components/checkbox/checkbox.js',
  'components/radio/radio.js',
  'components/switch/switch.js',
  'components/textarea/textarea.js',
  'components/select/select.js',
  'components/slider/slider.js',
  'components/badge/badge.js',
  'components/alert/alert.js',
  'components/progress/progress.js',
  'components/skeleton/skeleton.js',
  'components/tooltip/tooltip.js',
  'components/toast/toast.js',
  'components/dialog/dialog.js',
  'components/dropdown/dropdown.js',
  'components/popover/popover.js',
  'components/tabs/tabs.js',
  'components/accordion/accordion.js',
  'components/drawer/drawer.js'
];

export function assembleComponentCss(read = (p) => readFileSync(join(rootDir, p), 'utf8')) {
  const parts = COMPONENT_CSS_SOURCES.map((rel) => {
    const content = read(rel).trim();
    return `/* --- Source: ${rel} --- */\n${content}`;
  });

  return `/**
 * Aster Design System — Master Component Styles
 * Auto-generated by build-tools/build-components.js. Do not edit directly.
 * Canonical Sources: ${COMPONENT_CSS_SOURCES.join(', ')}
 */

${parts.join('\n\n')}
`;
}

export function assembleComponentJs(read = (p) => readFileSync(join(rootDir, p), 'utf8')) {
  const parts = COMPONENT_JS_SOURCES.map((rel) => {
    // Prefix local initializedRoots identifier per module to avoid top-level lexical collision in the bundle
    const modTag = rel.split('/')[1];
    const content = read(rel)
      .replace(/\binitializedRoots\b/g, `initializedRoots_${modTag}`)
      .trim();
    return `/* --- Source: ${rel} --- */\n${content}`;
  });

  return `/**
 * Aster Design System — Master Component Behavior Module (Browser ES Module)
 * Auto-generated by build-tools/build-components.js. Do not edit directly.
 * Canonical Sources: ${COMPONENT_JS_SOURCES.join(', ')}, components/index.js
 */

${parts.join('\n\n')}

/* --- Source: components/index.js (initAsterComponents) --- */
export function initAsterComponents(root = typeof document !== 'undefined' ? document : null, options = {}) {
  initButton(root, options);
  initInput(root, options);
  initTable(root, options);
  initCheckbox(root, options);
  initRadio(root, options);
  initSwitch(root, options);
  initTextarea(root, options);
  initSelect(root, options);
  initSlider(root, options);
  initBadge(root, options);
  initAlert(root, options);
  initProgress(root, options);
  initSkeleton(root, options);
  initTooltip(root, options);
  initToast(root, options);
  initDialog(root, options);
  initDropdown(root, options);
  initPopover(root, options);
  initTabs(root, options);
  initAccordion(root, options);
  initDrawer(root, options);
}
`;
}

export function buildComponents() {
  console.log('--- Building Aster Canonical Components ---');
  mkdirSync(join(rootDir, 'dist/css'), { recursive: true });
  mkdirSync(join(rootDir, 'dist/js'), { recursive: true });

  const cssOut = assembleComponentCss();
  const jsOut = assembleComponentJs();

  const cssDest = join(rootDir, 'dist/css/components.css');
  const jsDest = join(rootDir, 'dist/js/aster.js');

  writeFileSync(cssDest, cssOut, 'utf8');
  console.log(`✓ Compiled ${COMPONENT_CSS_SOURCES.length} CSS modules to dist/css/components.css`);

  const tokensCssPath = join(rootDir, 'dist/css/tokens.css');
  let tokensCss = '';
  try {
    tokensCss = readFileSync(tokensCssPath, 'utf8');
  } catch {
    tokensCss = '/* Run npm run build:tokens to compile tokens.css */\n';
  }
  const asterCss = `/**
 * Aster Design System — Master Stylesheet (Tokens + Components)
 * Auto-generated by build-tools/build-components.js. Do not edit directly.
 */

${tokensCss}

${cssOut}
`;
  writeFileSync(join(rootDir, 'dist/css/aster.css'), asterCss, 'utf8');
  console.log('✓ Compiled all-in-one stylesheet to dist/css/aster.css');

  writeFileSync(jsDest, jsOut, 'utf8');
  console.log(`✓ Compiled ${COMPONENT_JS_SOURCES.length} JS modules to dist/js/aster.js`);

  console.log('--- Component Build Complete ---');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    buildComponents();
  } catch (err) {
    console.error('Component build failed:', err);
    process.exit(1);
  }
}
