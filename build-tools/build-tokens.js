import StyleDictionary from 'style-dictionary';
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');

const buildDir = join(rootDir, 'dist/css/');
mkdirSync(buildDir, { recursive: true });

// Remove legacy compact density stylesheet if present
const legacyCompactCss = join(buildDir, 'density-compact.css');
if (existsSync(legacyCompactCss)) {
  rmSync(legacyCompactCss, { force: true });
}

// 1. Build Base (Primitives + Light Mode + Default Density)
const sdBase = new StyleDictionary({
  source: [
    'tokens/primitive/**/*.json',
    'tokens/semantic/light.json',
    'tokens/density/comfortable.json'
  ],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'as',
      buildPath: 'dist/css/',
      files: [
        {
          destination: 'base.css',
          format: 'css/variables',
          options: {
            outputReferences: true,
            selector: ':root, [data-theme="light"]'
          }
        }
      ]
    }
  }
});

// 2. Build Dark Mode Override
const sdDark = new StyleDictionary({
  include: ['tokens/primitive/**/*.json'],
  source: ['tokens/semantic/dark.json'],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'as',
      buildPath: 'dist/css/',
      files: [
        {
          destination: 'theme-dark.css',
          format: 'css/variables',
          filter: (token) => token.path[0] === 'semantic',
          options: {
            outputReferences: true,
            selector: '[data-theme="dark"]'
          }
        }
      ]
    }
  }
});

console.log('--- Building Aster Design Tokens ---');
await sdBase.buildAllPlatforms();
await sdDark.buildAllPlatforms();

// 3. Combine into a single master dist/css/tokens.css file for seamless consumption
const baseCss = readFileSync(join(buildDir, 'base.css'), 'utf8');
const darkCss = readFileSync(join(buildDir, 'theme-dark.css'), 'utf8');

const combinedCss = `/**
 * Aster Design System — Master Token Stylesheet
 * Auto-generated by Style Dictionary. Do not edit directly.
 * Modes: Light (default), Dark ([data-theme="dark"])
 */

${baseCss}
${darkCss}
`;

writeFileSync(join(buildDir, 'tokens.css'), combinedCss, 'utf8');
console.log('✓ Successfully generated dist/css/tokens.css');
