import StyleDictionary from 'style-dictionary';
import { readFileSync, writeFileSync } from 'fs';

async function build() {
  console.log('--- Building Aster Production Design Tokens ---');

  // 1. Build Base (:root) — Primitives + Semantic Light + Default Comfortable Density
  const sdLight = new StyleDictionary({
    source: [
      'tokens/primitive/color.json',
      'tokens/primitive/typography.json',
      'tokens/primitive/space.json',
      'tokens/primitive/radius.json',
      'tokens/primitive/elevation.json',
      'tokens/semantic/light.json',
      'tokens/density/comfortable.json'
    ],
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'as',
        buildPath: 'dist/css/',
        files: [
          {
            destination: 'tokens-light.css',
            format: 'css/variables',
            options: {
              selector: ':root',
              outputReferences: false
            }
          }
        ]
      }
    }
  });

  await sdLight.buildAllPlatforms();
  console.log('✓ Compiled light mode, primitives, and default density to dist/css/tokens-light.css');

  // 2. Build Dark Theme Overrides ([data-theme="dark"])
  const sdDark = new StyleDictionary({
    source: [
      'tokens/primitive/color.json',
      'tokens/primitive/typography.json',
      'tokens/primitive/space.json',
      'tokens/primitive/radius.json',
      'tokens/primitive/elevation.json',
      'tokens/semantic/dark.json'
    ],
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'as',
        buildPath: 'dist/css/',
        files: [
          {
            destination: 'tokens-dark.css',
            format: 'css/variables',
            filter: (token) => token.path.includes('semantic'),
            options: {
              selector: '[data-theme="dark"]',
              outputReferences: false
            }
          }
        ]
      }
    }
  });

  await sdDark.buildAllPlatforms();
  console.log('✓ Compiled dark mode semantic overrides to dist/css/tokens-dark.css');

  // 3. Build Compact Density Overrides ([data-density="compact"])
  const sdCompact = new StyleDictionary({
    source: [
      'tokens/density/compact.json'
    ],
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'as',
        buildPath: 'dist/css/',
        files: [
          {
            destination: 'density-compact.css',
            format: 'css/variables',
            options: {
              selector: '[data-density="compact"]',
              outputReferences: false
            }
          }
        ]
      }
    }
  });

  await sdCompact.buildAllPlatforms();
  console.log('✓ Compiled compact density overrides to dist/css/density-compact.css');

  // 4. Combine into Master dist/css/tokens.css
  const lightContent = readFileSync('dist/css/tokens-light.css', 'utf8');
  const darkContent = readFileSync('dist/css/tokens-dark.css', 'utf8');
  const compactContent = readFileSync('dist/css/density-compact.css', 'utf8');

  const masterContent = `/**
 * Aster Design System — Master Tokens
 * Auto-generated by Style Dictionary v5. Do not edit directly.
 * Canonical Source: tokens/primitive/, tokens/semantic/, tokens/density/
 */

${lightContent}

${darkContent}

${compactContent}
`;

  writeFileSync('dist/css/tokens.css', masterContent);
  console.log('✓ Combined master stylesheet written to dist/css/tokens.css');

  console.log('--- Production Token Build Complete ---');
}

build().catch((err) => {
  console.error('Token build failed:', err);
  process.exit(1);
});
